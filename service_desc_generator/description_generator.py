import json
import os
import sys

sys.path.append(
    f"{os.path.dirname(os.path.abspath(__file__))}/.."
)

from ollama import chat

from data.dataset_builder.config import (
    GENERAL_SUBJECTS,
    SERVICE_SETS,
)


class ServiceDescriptionGenerator:

    def __init__(
        self,
        concept_path="./concept_extraction.json",
        out_path="./service_descriptions.json",
        model="llama3.1:8b",
        verbose=True,
    ):
        self.concept_path = concept_path
        self.out_path = out_path
        self.model = model
        self.verbose = verbose

        # 10 specialist services
        self.specialist_services = SERVICE_SETS[10]

        # Subjects used to represent the general fallback
        self.general_subjects = GENERAL_SUBJECTS

        self.concepts = self._load_concepts()

    def _log(self, message):
        """
        Print messages when verbose mode is enabled.
        """
        if self.verbose:
            print(message)

    def _load_concepts(self):
        """
        Load concept profiles generated by concept_extractor.py.
        """

        with open(self.concept_path, "r") as f:
            concepts = json.load(f)

        self._log(
            f"[LOAD] concept profiles: {len(concepts)}"
        )

        return concepts

    def _build_description_prompt(
        self,
        service,
        core_concepts
    ):
        """
        Build the description-generation prompt
        for one specialist service.
        """

       
        service_name = service.replace("_", " ")

        concept_list = ", ".join(core_concepts)

        prompt = f"""
You are writing a semantic description for a topic-classification service.

SERVICE:
{service_name}

CORE CONCEPTS:
{concept_list}

TASK:
Write one concise semantic description of the subject matter handled
by this service.

GROUNDING RULE:
The supplied CORE CONCEPTS are the complete source of subject-matter
information for this description.

All content-bearing terminology should come directly from the supplied
core concepts, using the same or nearly identical wording.

Do NOT introduce additional topics, examples, properties, sub-concepts,
or factual details that are not explicitly present in the core concepts.

For example, if the supplied concept is:
"electromagnetic spectrum regions"

do NOT write:
"electromagnetic spectrum regions including visible light"

because "visible light" was not supplied.

Rules:
- Maximum 50 words.
- Consider the FULL core-concepts list.
- Include as many supplied core concepts as reasonably possible.
- Preserve the wording of supplied concepts exactly or near-verbatim.
- Prefer concrete supplied concepts over broader paraphrases.
- Do NOT add explanatory examples or narrower examples.
- Do NOT infer factual relationships between separate concepts.
- When concepts are separate, mention them separately rather than
  inventing a relationship between them.
- Do NOT assign a concept to a religion, theory, person, system,
  category, or discipline unless that relationship is explicitly
  stated in the supplied concept.
- Do NOT replace specific concepts with vague umbrella categories.
- Use the natural-language service name "{service_name}" if the service
  name is mentioned.
- Never write underscores in the description.
- Do NOT use words such as "route", "routing", "path", "navigate",
  "travel", or "optimize travel".
- Do NOT mention datasets, validation data, benchmarks, or concept extraction.
- Avoid filler phrases such as "covers a broad range",
  "among other topics", or "classifies questions into topic categories".
- Output ONLY the description text.
""".strip()

        return prompt


    def _build_general_description_prompt(
        self,
        general_concepts
    ):
        """
        Build the description-generation prompt
        for the GENERAL service.
        """

        subject_blocks = []

        for subject, concepts in general_concepts.items():

            subject_name = subject.replace("_", " ")

            subject_blocks.append(
                f"""
SOURCE DOMAIN:
{subject_name}

CORE CONCEPTS:
{", ".join(concepts)}
""".strip()
        )

        formatted_subjects = "\n\n".join(
            subject_blocks
        )

        prompt = f"""
You are writing a semantic description for a topic-classification
service called general.

The service is represented by the following source domains:

{formatted_subjects}

TASK:
Write one concise semantic description of the subject matter represented
by these source domains.

GROUNDING RULE:
The supplied CORE CONCEPTS are the complete source of subject-matter
information for this description.

Do NOT introduce additional topics, examples, properties, sub-concepts,
or factual details that are not explicitly present in the supplied
core concepts.

Rules:
- Include concepts from BOTH source domains.
- Consider the FULL core-concepts list from both domains.
- Include as many supplied concepts as reasonably possible.
- Complete semantic coverage is more important than a strict 50-word limit.
- Preserve supplied terminology exactly or near-verbatim.
- Do NOT add explanatory or narrower examples.
- Do NOT infer factual relationships between separate concepts.
- When concepts are separate, mention them separately.
- Do NOT replace specific concepts with vague umbrella categories.
- Describe subject matter only.
- Do NOT mention that general is a fallback, catch-all, or default service.
- Never write underscores in the description.
- Do NOT mention datasets, validation data, benchmarks, or concept extraction.
- Do NOT use words such as "route", "routing", "path", "navigate", or "travel".
- Output ONLY the description text.
""".strip()

        return prompt

    def _call_llm(self, prompt):
        """
        Send a prompt to the LLM and return
        the generated description.
        """

        response = chat(
            model=self.model,
            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            options={
                "temperature": 0
            },
        )

        return response.message.content.strip()

    def _get_general_concepts(self):
        """
        Collect full core_concepts per GENERAL_SUBJECTS entry,
        keyed by subject, for the general fallback service.
        """

        general_concepts = {}

        for subject in self.general_subjects:

            data = self.concepts.get(subject)

            if data is None or "error" in data:
                self._log(
                    f"[WARN] missing/failed general source: "
                    f"{subject}"
                )
                continue

            general_concepts[subject] = data["core_concepts"]

        return general_concepts

    def _build(self):
        """
        Generate descriptions for:
        - 10 specialist services
        - 1 general fallback service
        """

        service_descriptions = {}

        total = len(
            self.specialist_services
        )

        self._log(
            f"\n[START] generating "
            f"{total} specialist descriptions"
        )

        # --------------------------------
        # Specialist services
        # --------------------------------

        for idx, service in enumerate(
            self.specialist_services,
            start=1
        ):

            data = self.concepts.get(service)

            if data is None or "error" in data:

                self._log(
                    f"[{idx}/{total}] "
                    f"[WARN] skipping {service}"
                )

                continue

            self._log(
                f"\n[{idx}/{total}] "
                f"generating: {service}"
            )

            self._log(
                f"[{idx}/{total}] "
                f"SERVICE: {service}"
            )
            self._log(
                f"[{idx}/{total}] "
                f"CORE CONCEPTS: {data['core_concepts']}"
            )

            prompt = (
                self._build_description_prompt(
                    service=service,
                    core_concepts=data["core_concepts"]
                )
            )

            description = self._call_llm(
                prompt
            )

            service_descriptions[
                service
            ] = description

            word_count = len(
                description.split()
            )

            self._log(
                f"[{idx}/{total}] "
                f"[BUILT] {service} "
                f"({word_count} words)"
            )
            self._log(
                f"[{idx}/{total}] "
                f"DESCRIPTION: {description}"
            )

        # --------------------------------
        # General fallback service
        # --------------------------------

        self._log(
            "\n[GENERAL] generating fallback description"
        )

        general_concepts = (
            self._get_general_concepts()
        )

        self._log(
            f"[GENERAL] SERVICE: general"
        )
        self._log(
            f"[GENERAL] CORE CONCEPTS: {general_concepts}"
        )

        general_prompt = (
            self._build_general_description_prompt(
                general_concepts
            )
        )

        general_description = (
            self._call_llm(
                general_prompt
            )
        )

        service_descriptions[
            "general"
        ] = general_description

        general_word_count = len(
            general_description.split()
        )

        self._log(
            f"[GENERAL] [BUILT] general "
            f"({general_word_count} words)"
        )
        self._log(
            f"[GENERAL] DESCRIPTION: {general_description}"
        )

        return service_descriptions

    def save(
        self,
        service_descriptions
    ):
        """
        Save final service descriptions.
        """

        with open(
            self.out_path,
            "w"
        ) as f:

            json.dump(
                service_descriptions,
                f,
                indent=2
            )

        self._log(
            f"\n[DONE] "
            f"{len(service_descriptions)} "
            f"descriptions saved to "
            f"{self.out_path}"
        )

    def build_and_save(self):
        """
        Run description generation
        and save the results.
        """

        descriptions = self._build()

        self.save(
            descriptions
        )

        return descriptions


if __name__ == "__main__":

    generator = (
        ServiceDescriptionGenerator()
    )

    generator.build_and_save()